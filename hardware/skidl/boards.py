def layers_of(board):
    """1 — односторонняя (медь только B.Cu), 2 — двусторонняя."""
    return BOARDS[board].get("layers", 1)


def board_of(block):
    for name, b in BOARDS.items():
        if block in b["blocks"]:
            return name
    raise KeyError(f"подсхема {block} не отнесена ни к одной плате (boards.py)")
