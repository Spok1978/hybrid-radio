/*
 * board_pins.h — раскладка выводов IP-Radio на плате
 *                Waveshare ESP32-P4-WIFI6-Touch-LCD-5.
 *
 * Все номера — из docs/30-pin-assignment.md, вариант выбирается ниже.
 * Ограничения, из которых раскладка выведена (docs/26-firmware-spec.md, §2.7):
 *
 *   - кнопка питания обязана сидеть на GPIO3, GPIO4 или GPIO5: будить
 *     из глубокого сна умеет только домен VDD_LP, то есть GPIO0…GPIO15;
 *   - GPIO34 — strapping-вывод (источник JTAG), занимать в последнюю очередь;
 *   - GPIO7/GPIO8 — штатная шина I²C платы, подтяжки 2,2 кОм к 3,3 В уже
 *     стоят, тюнер и расширитель садятся на неё без своих резисторов;
 *   - GPIO9…GPIO13 — штатная шина I²S платы (кодек ES8311 и ES7210),
 *     на гребёнку НЕ выведены; наш I²S идёт на другие выводы через
 *     матрицу GPIO;
 *   - GPIO35, GPIO37, GPIO38 заняты платой (автосброс и отладочный UART),
 *     на них ничего вешать нельзя.
 *
 * ВНИМАНИЕ. Точная нумерация КОНТАКТОВ гребёнки (какой контакт разъёма
 * соответствует какому GPIO) ещё не сверена — см. docs/26, §2.5.
 * Здесь заданы номера GPIO, а не номера контактов разъёма.
 */

#pragma once

/* ------------------------------------------------------------------ *
 *  Выбор конфигурации
 * ------------------------------------------------------------------ */

/* 1 — вариант 1: восемь кнопок пресетов на расширителе MCP23017
 * 0 — вариант 2-бис: пять кнопок пресетов прямо на выводах            */
/* БЫЛО 1, СТАЛО 0.
 *
 * Единица означала «кнопки пресетов и MODE сидят на MCP23017».
 * Драйвера MCP23017 в прошивке нет — расширитель упоминается только
 * здесь и в таблице сканера шины. Из-за этого вся таблица кнопок
 * собиралась в ветке #else, то есть при сборке по умолчанию восемь
 * кнопок пресетов и кнопка режима были мертвы.
 *
 * Расширитель пока не куплен. Ставим 0: пять пресетов и MODE работают
 * напрямую с выводов. Когда появится железо и драйвер — вернуть 1.
 *
 * 2026-10-19: ВЕРНУЛИ 1. Расширитель на шине (0x20, виден сканером при
 * запуске), восемь кнопок подключены, драйвер - в ipradio_input.c
 * (опрос портов по I²C в цикле ввода). */
#define IPRADIO_USE_IO_EXPANDER   1

/* Сколько ячеек пресетов показывать и обслуживать.
 *
 * Раньше экран всегда рисовал восемь, а кнопок без расширителя пять:
 * три ячейки нельзя было нажать ничем. Теперь число одно на обе
 * стороны и следует за железом. В хранилище по-прежнему восемь ячеек -
 * это правильно, лишние просто не показываются. */
/* Сколько ФИЗИЧЕСКИХ кнопок пресетов на приборе.
 *
 * Это не размер банка станций - тот задаётся IPRADIO_PRESET_MAX
 * в ipradio_storage.h и сейчас равен десяти. Кнопки адресуют первые
 * IPRADIO_PRESET_BUTTONS ячеек, до остальных достают только пальцем
 * по экрану. Числа разные намеренно.
 *
 * Рядом раньше жил второй макрос, PRESET_BUTTON_COUNT, с теми же
 * значениями. Его никто не использовал ни разу - удалён 2026-09-15.
 * Держать два имени для одного понятия значит однажды поправить
 * одно и забыть другое. */
#if IPRADIO_USE_IO_EXPANDER
#define IPRADIO_PRESET_BUTTONS   8
#else
#define IPRADIO_PRESET_BUTTONS   5
#endif

/* ------------------------------------------------------------------ *
 *  Штатные шины платы
 * ------------------------------------------------------------------ */

#define PIN_I2C_SDA               7   /* ESP_I2C_SDA, выведена на гребёнку */
#define PIN_I2C_SCL               8   /* ESP_I2C_SCL                       */

#define I2C_ADDR_TUNER_SEQ     0x10   /* RDA5807M, последовательный доступ */
#define I2C_ADDR_TUNER_RANDOM  0x11   /* RDA5807M, доступ к одному регистру */
#define I2C_ADDR_EXPANDER      0x20   /* MCP23017                          */
/* Заняты платой: GT911 0x5D или 0x14, ES8311 0x18, ES7210 0x40 —
 * с нашими адресами не пересекаются.                                   */

/* Штатный усилитель платы NS4150B. На гребёнку не выведен, управляется
 * изнутри прошивки. Держим низким: усилитель платы не используется,
 * звук идёт через наш TPA3118.                                         */
#define PIN_BOARD_PA_CTRL        53

/* ------------------------------------------------------------------ *
 *  Отладочные выводы в журнал
 * ------------------------------------------------------------------ *
 *
 * Всё, что печатается не по делу, а чтобы разобраться, живёт под
 * этими ключами. Раньше такие строки просто лежали в коде с пометкой
 * «УБРАТЬ», и убирать их приходилось вручную, по одной, рискуя задеть
 * рабочую логику.
 *
 * Держать их включёнными во время отладки - нормально. Но мусор
 * в журнале мешает разбирать настоящие отказы: важная строка тонет
 * среди пульсов. Поэтому перед тем, как отдавать прибор, все три
 * ставятся в 0.
 */

/* Самопроверка формата хранилища при запуске.
 *
 * Гоняет печать и разбор в памяти, карту не трогает. Занимает
 * доли секунды и печатает результат построчно. Держать включённой
 * во время работы над форматом обязательно: ошибка в разборе
 * не падает, она молча теряет записанные станции.
 *
 * Подробности - ipradio_selftest.h. */
#define IPRADIO_SELFTEST            1

/* Раз в три секунды: сколько прошло и сколько свободной внутренней
 * памяти. Нужен, чтобы отличить «встала вся система» от «встал
 * только интерфейс». */
#define IPRADIO_DEBUG_MAIN_PULSE    1

/* Раз в пять секунд: сколько байт ушло в I²S и с какой скоростью.
 * Единственный способ убедиться, что звук течёт, пока не подключён
 * свой ЦАП и слушать нечем. Плюс печать уровня, ушедшего в регулятор
 * громкости. */
#define IPRADIO_DEBUG_AUDIO_FLOW    1

/* Полный дамп регистров кодека платы после настройки формата.
 * Им отличают «кодек молчит» от «до кодека не доходит» - именно
 * так нашлась драка двух шин I²C за одни выводы. */
#define IPRADIO_DEBUG_CODEC_REGS    1

/* Прогон на выносливость: прибор сам переключает интернет-станции
 * сорок раз подряд, каждый пятый раз ищет в каталоге. Только для
 * проверки памяти на столе - в работе ДОЛЖЕН быть 0, иначе через
 * минуту после включения прибор начнёт листать станции сам.
 * Подробности - ipradio_soak.h. */
#define IPRADIO_DEBUG_SOAK          0

/* Проверка приёма эфира: через 5 с после загрузки проход по FM-диапазону
 * и уровень сигнала каждой найденной станции в журнал (строки «ПРИЁМ»).
 * Только для стола; в работе 0 - иначе прибор после каждого включения
 * перебирает частоты. Подробности - ipradio_fmprobe.c. */
#define IPRADIO_DEBUG_FM_PROBE      0

/* Сырые группы 0 RDS в журнал: какая пара знаков пришла и её байты.
 * Нужна, чтобы разбирать имена станций по данным, а не догадкой. */
#define IPRADIO_DEBUG_RDS_RAW       0

/* Ввод: состояние портов MCP23017 при каждом изменении и каждое
 * событие кнопки - чтобы видеть, доходит ли нажатие до прошивки. */
#define IPRADIO_DEBUG_INPUT         1

/* ОДНОРАЗОВО (2026-10-19): при запуске записать в интернет-банк
 * ячейки 1, 6, 7, 8 (Наше радио, Бизнес FM, Русское радио, Маяк -
 * адреса из каталога radio-browser) и напечатать весь банк. Каждый
 * запуск с единицей перезаписывает эти ячейки - после проверки 0. */
#define IPRADIO_SEED_NET_PRESETS    0   /* 2026-10-19: записано (дважды), ESP_OK */

/* ОДНОРАЗОВО (2026-10-19): записать в эфирный банк ячейки 1…5 - FM
 * 98,7 / 100,7 / 105,2 / 107,7 / 96,6 МГц (частоты заказчика) - и
 * напечатать банк. После проверки журнала - 0. */
#define IPRADIO_SEED_FM_PRESETS     0   /* 2026-10-19: записано (дважды), ESP_OK */

/* ВРЕМЕННО (2026-09-05): гнать звук в штатный кодек платы ES8311,
 * а не в наш PCM5102A.
 *
 * Свой ЦАП и усилитель ещё не подключены, услышать проигрывание
 * нечем. У платы есть собственный тракт с разъёмом для динамика,
 * и он исправен - просто мы его не используем. На время проверки
 * включаем его. Подробности - ipradio_board_codec.h.
 *
 * Поставить 0, как только подключим свой ЦАП. */
#define IPRADIO_USE_BOARD_CODEC   1

/* ------------------------------------------------------------------ *
 *  Наш звуковой тракт: PCM5102A по I²S
 * ------------------------------------------------------------------ */

#define PIN_I2S_BCK              46
#define PIN_I2S_LRCK             47
#define PIN_I2S_DIN              48
/* SCK у PCM5102A сажается на землю: внутренняя ФАПЧ получает тактирование
 * из BCK (даташит TI, «Integrated High-Performance Audio PLL with BCK
 * Reference to Generate SCK Internally»). Четвёртая линия не нужна.     */

#define PIN_AMP_SD               49  /* приглушение нашего TPA3118        */

/* ------------------------------------------------------------------ *
 *  Органы управления
 * ------------------------------------------------------------------ */

#define PIN_POWER_BUTTON          3  /* ТОЛЬКО GPIO3/4/5 — LP-домен       */

#define PIN_ENC1_A               21
#define PIN_ENC1_B               22
#define PIN_ENC1_BTN             28  /* ОК / играть                       */

#define PIN_ENC2_A               29
#define PIN_ENC2_B               30
#define PIN_ENC2_BTN             31  /* Mute вкл/выкл                     */

#if IPRADIO_USE_IO_EXPANDER

  #define PIN_EXPANDER_INT       32
  /* Кнопки пресетов 1…7 — линии GPA0…GPA6 расширителя, пресет 8 — GPB0,
   * MODE — GPB1 (см. ниже). Номер линии: GPAn = n, GPBn = 8 + n.
   * Кнопка замыкает линию на землю, подтяжка внутренняя (GPPU).
   * GPA7 и GPB7 у MCP23017 только выходы (Microchip DS20001952E) —
   * кнопки на них не вешать (docs/33, §10).                            */
  #define EXP_LINE_PRESET_BASE    0   /* пресеты 1…7: линии 0…6 */
  /* 2026-10-19: на макете пресет 8 припаян к GPB0 (перенесён с GPA7),
   * поэтому MODE - на GPB1. Схема (carrier.py, docs/33) приведена
   * к этой раскладке. */
  #define EXP_LINE_PRESET_8       8   /* GPB0 */
  #define EXP_LINE_MODE           9   /* GPB1 */

  /* Свободны про запас: GPIO4, GPIO5, GPIO34, GPIO50, GPIO51, GPIO52
   * и семь линий расширителя.                                           */

#else

  #define PIN_MODE_BUTTON        32
  #define PIN_PRESET_1            4
  #define PIN_PRESET_2            5
  #define PIN_PRESET_3           50
  #define PIN_PRESET_4           51
  #define PIN_PRESET_5           52

  /* Свободен про запас: GPIO34 (strapping, держим в резерве).            */

#endif

