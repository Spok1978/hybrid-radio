/* Заглушка FreeRTOS для сборки на машине разработчика.
 *
 * ЗАЧЕМ. Автомат состояния зовёт очереди, мьютексы и создание задач.
 * Всё это часть операционной системы, которая живёт на плате. Чтобы
 * проверять логику автомата здесь, эти вызовы надо чем-то ответить.
 *
 * ЧТО ИМЕННО ПОДДЕЛЫВАЕТСЯ. Очередь - обычный массив: очередь и есть
 * массив, только без защиты от одновременного доступа, а тест идёт
 * в один поток. Мьютексы - пустышки: блокироваться не от кого.
 * Создание задачи - тоже пустышка, и это главное: задачу мы НЕ
 * запускаем, а разбираем события вручную, шаг за шагом. Иначе в тест
 * вернулись бы планировщик и время, ради ухода от которых он и нужен.
 *
 * ЧЕГО ЭТИМ НЕ ПРОВЕРИТЬ. Гонок между задачами, переполнения стека,
 * нехватки памяти, сторожа, таймингов - вообще ничего, что связано
 * с одновременностью. Это остаётся за платой. Заглушки снимают
 * с неё только тот класс ошибок, который до платы доезжать не должен.
 *
 * Подделывать сам FreeRTOS не страшно: он написан не нами и проверен
 * своими авторами. Мы проверяем СВОЙ код и вправе считать, что
 * очередь работает как очередь.
 */
